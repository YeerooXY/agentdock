'use strict';
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const { Projects } = require('../electron/projects.cjs');
const { Results } = require('../electron/results.cjs');
const { openPage } = require('./ui-navigation.cjs');
const root = path.resolve(__dirname, '..'), parent = path.join(root, 'test-data');
fs.mkdirSync(parent, { recursive: true });
const profile = fs.mkdtempSync(path.join(parent, 'project-workspace-'));
const repo = path.join(profile, 'repo'); fs.mkdirSync(repo); fs.writeFileSync(path.join(repo, 'main.py'), 'def launch(): pass\n');
fs.writeFileSync(path.join(profile, 'settings.json'), JSON.stringify({ setupComplete: true, restoreConsoles: false }));
const projects = new Projects(profile);
const project = projects.save({ name: 'Workspace fixture', goals: 'Project goals', folders: [{ path: repo }] });
const results = new Results(profile);
results.add({ text: 'Requested output body', title: 'Requested output', kind: 'report' }, { projectId: project.id, project: repo, trusted: true });
results.add({ text: 'Unassigned output', title: 'Unassigned output', kind: 'report' }, { trusted: true });
const { ProjectKnowledge } = require('../electron/project-knowledge.cjs');
const seed = require('../tests/fixtures/knowledge/sections.json').greenfieldProposed;
new ProjectKnowledge(profile).commit(project.id, { operationId: 'seed', changes: Array.from({ length: 25 }, (_, i) => { const id = `sec_fixture_${String(i).padStart(2, '0')}`; return { id, expectedVersion: 0, section: { ...seed, id, title: `Fixture section ${i}` } }; }) });
let app;
(async () => {
  app = await electron.launch({ args: [root, '--smoke-test', `--data-dir=${profile}`], timeout: 30000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('.session-grid');
  const call = (method, payload) => page.evaluate(async ([method, payload]) => { const r = await window.dock.call(method, payload); if (!r.ok) throw Error(r.error); return r.value; }, [method, payload]);
  const focused = async () => assert.notEqual(await page.evaluate(() => document.activeElement.tagName), 'BODY');
  assert.equal(await page.locator('.sidebar [data-page=tasks], .sidebar [data-page=results], #results-count').count(), 0);
  assert.equal((await call('state')).settings.knowledgeMode, 'off');
  await assert.rejects(call('knowledge.inventory', { id: project.id }), /off/);
  await openPage(page, 'projects');
  await page.locator(`[data-project-inspect="${project.id}"]`).focus(); await page.keyboard.press('Enter');
  await page.locator('#project-workspace-title').waitFor(); await focused();
  await page.locator('[data-project-tab=outputs]').focus(); await page.keyboard.press('Space');
  await page.getByRole('button', { name: 'Requested output', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Unassigned output', exact: true }).count(), 0);
  await focused(); await page.keyboard.press('Shift+Tab'); await focused(); await page.keyboard.press('Tab'); await focused();
  await page.locator('[data-project-tab=knowledge]').click();
  await page.getByText('Project knowledge is off.', { exact: true }).waitFor();
  await call('projects.knowledgeMode', { id: project.id, mode: 'read' });
  await page.getByText('Project knowledge is off.', { exact: true }).waitFor();
  await call('settings', { knowledgeMode: 'read' });
  await page.locator('[data-project-knowledge-more]').waitFor();
  assert.equal(await page.locator('[data-project-knowledge-read]').count(), 20);
  await page.locator('[data-project-knowledge-more]').focus(); await page.keyboard.press('Space');
  await page.waitForFunction(() => document.querySelectorAll('[data-project-knowledge-read]').length === 25); await focused();
  await page.locator('[data-project-inventory]').focus(); await page.keyboard.press('Enter');
  await page.locator('[data-project-knowledge-read]').first().waitFor(); await focused();
  assert.match(await page.locator('.knowledge-assurance').innerText(), /unverified/i);
  const artifacts = path.join(root, 'artifacts', 'project-workspace'); fs.mkdirSync(artifacts, { recursive: true });
  await page.screenshot({ path: path.join(artifacts, 'desktop.png') });
  await page.setViewportSize({ width: 640, height: 900 });
  await page.screenshot({ path: path.join(artifacts, 'narrow.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('[data-project-knowledge-more]').click();
  await page.locator('[data-project-knowledge-read]').filter({ hasText: 'Inventory:' }).click();
  await page.locator('.execution-report[open]').waitFor();
  assert.match(await page.locator('.execution-report pre').innerText(), /Source contents were not read/);
  await page.keyboard.press('Escape'); await focused();
  await page.locator('[data-project-knowledge-mode]').selectOption('off');
  await page.getByText('Project knowledge is off.', { exact: true }).waitFor(); await focused();
  await assert.rejects(call('knowledge.directory', { id: project.id }), /off/);
  await page.locator('[data-project-knowledge-mode]').selectOption('inherit');
  await page.locator('[data-project-knowledge-read]').first().waitFor(); await focused();
  await page.locator('[data-project-tab=overview]').click();
  await page.locator('[data-project-initialize]').focus(); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-project-initialize]')?.textContent === 'Refresh source map');
  await focused();
  assert.equal((await call('knowledge.state', { id: project.id })).initialized, true);
  await page.getByRole('button', { name: 'Read overview', exact: true }).click();
  await page.locator('.execution-report[open]').waitFor();
  assert.match(await page.locator('.execution-report pre').innerText(), /selected source/);
  await page.keyboard.press('Escape'); await focused();
  await openPage(page, 'settings');
  const mode = page.locator('[data-setting=knowledgeMode]');
  assert.equal(await mode.locator('option[value=automatic]').getAttribute('disabled'), '', await mode.evaluate(el => el.outerHTML));
  await page.getByText('Documentation worker', { exact: true }).click();
  const worker = page.locator('#knowledge-worker-form');
  await worker.locator('[name=accountId]').selectOption('opencode:strata');
  await worker.locator('[name=model]').fill('fixture-model');
  await worker.locator('[name=funding]').selectOption('local');
  await worker.getByRole('button', { name: 'Save worker' }).focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => !document.querySelector('[data-setting=knowledgeMode] option[value=automatic]').disabled);
  await focused();
  await mode.selectOption('automatic'); await focused();
  assert.equal((await call('state')).settings.knowledgeWorker.funding, 'local');
  await mode.selectOption('read'); await focused();
  await page.reload(); await page.waitForSelector('.session-grid');
  assert.equal((await call('state')).settings.knowledgeMode, 'read');
  await openPage(page, 'results'); await page.locator('[data-wb=project-folder]').filter({ hasText: 'Other' }).click(); await page.getByText('Unassigned output', { exact: true }).waitFor();
  await openPage(page, 'tasks'); await page.getByRole('heading', { name: 'Worker history' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS Projects workspace, output scope, optional knowledge, local inventory, persistence and keyboard focus');
  await app.close(); app = null;
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (app) await app.close().catch(() => {});
  assert.equal(path.dirname(fs.realpathSync(profile)), fs.realpathSync(parent)); fs.rmSync(profile, { recursive: true, force: true });
});
