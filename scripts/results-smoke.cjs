'use strict';
const { openPage } = require('./ui-navigation.cjs');
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { Results } = require('../electron/results.cjs');
const zip = require('./fixtures/zip.cjs');
const root = path.resolve(__dirname, '..'), parent = path.join(root, 'test-data'), out = path.join(root, 'artifacts/results-check');
fs.mkdirSync(out, { recursive: true }); fs.mkdirSync(parent, { recursive: true });
const work = fs.mkdtempSync(path.join(parent, 'results-desktop-')), profile = path.join(work, 'profile'), project = path.join(work, 'project');
fs.mkdirSync(profile); fs.mkdirSync(project);
fs.writeFileSync(path.join(profile, 'settings.json'), JSON.stringify({ setupComplete: true, restoreConsoles: false, consoleDefaults: { provider: 'shell', cwd: project } }));
const source = path.join(project, 'verification.zip');
fs.writeFileSync(source, zip([{ name: 'screens/dock.png', data: fs.readFileSync(path.join(root, 'assets/icon.png')) }, { name: 'checks/report.md', data: fs.readFileSync(path.join(__dirname, 'fixtures/result-preview.md')) }, { name: 'changes/app.diff', data: '-const ready = false;\n+const ready = true;' }]));
const context = { project, consoleName: 'Paddock', consoleKey: 'dock-fixture', turnId: 'restore-fixture', git: { branch: 'main', commit: 'a'.repeat(40), repository: project, detached: false, dirty: false } };
const results = new Results(profile), archive = results.add({ file: source, title: 'Verification files', kind: 'test' }, context);
const diff = { version: 2, git: { before: context.git, after: { ...context.git, commit: 'b'.repeat(40), dirty: true } }, notes: [], changes: [{ file: 'electron/sessions.cjs', type: 'modified', patch: '--- electron/sessions.cjs\n+++ electron/sessions.cjs\n@@ -1 +1 @@\n-saveAfterReply();\n+saveChatAtStart();' }] };
const code = results.add({ text: JSON.stringify(diff), ext: '.json', title: '1 changed file', kind: 'code' }, context);
const pictures = ['Desktop layout','Phone layout'].map(title => results.add({ file:path.join(root,'assets/icon.png'), title, kind:'screenshot' }, { ...context, trusted:true }));
const metadata = results.add({ text:JSON.stringify({internalTrace:'not a useful preview',requests:3}),ext:'.json',title:'Supporting test data',kind:'test',summary:'3 requests checked.' },context);
results.finishGit(context.turnId, context.consoleKey, project, diff.git.after);
let app;
(async () => {
  app = await electron.launch({ args: [root, '--smoke-test', `--data-dir=${profile}`], timeout: 30000 });
  const page = await app.firstWindow(), errors = []; page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(20000);
  await page.locator('.session-grid').waitFor();
  const call = (method, payload) => page.evaluate(async ([m, p]) => { const r = await window.dock.call(m, p); if (!r.ok) throw Error(r.error); return r.value; }, [method, payload]);
  const state = await call('state'), previews = {};
  previews[code.id] = await call('workbench.results.preview', code.id);
  previews[archive.id] = await call('workbench.results.preview', archive.id);
  for (const item of pictures) previews[item.id] = await call('workbench.results.preview', item.id);
  previews[metadata.id] = await call('workbench.results.preview', metadata.id);
  for (let i = 0; i < 3; i++) previews[archive.id + ':' + i] = await call('workbench.results.preview', { id: archive.id, entry: i });
  fs.writeFileSync(path.join(out, 'fixture.json'), JSON.stringify({ state, previews, archiveId: archive.id, codeId: code.id, pictureIds:pictures.map(x=>x.id), metadataId:metadata.id }));
  await openPage(page, 'results');
  await page.locator(`img[data-result-image="${archive.id}"]`).waitFor();
  await page.waitForFunction(id => document.querySelector(`img[data-result-image="${id}"]`)?.naturalWidth > 0, archive.id);
  assert.match(await page.locator('.result-batch-heading .result-branch').innerText(), /main · bbbbbbbb · Uncommitted changes/);
  assert.equal(await page.locator('.result-image-group').count(),1);
  assert.equal(await page.locator('.result-console-heading h2').innerText(),'project', 'Working folder is not the console name');
  await page.getByRole('button',{name:'Browse 2 pictures',exact:true}).click(); await page.locator('.result-full-image').waitFor();
  assert.equal((await call('state')).workbench.results.filter(x=>x.seenAt).length,1,'Opening one picture marks only that picture');
  const active = await page.locator('.result-filmstrip [aria-current=true]').getAttribute('data-id');
  await page.keyboard.press(active === pictures[0].id ? 'ArrowRight' : 'ArrowLeft');
  await page.waitForFunction(() => document.querySelectorAll('.result-filmstrip button[aria-label$="viewed"]:not([aria-label$="not viewed"])').length===2);
  assert.equal((await call('state')).workbench.results.filter(x=>x.seenAt).length,2);
  await page.screenshot({path:path.join(out,'windows-gallery-viewer.png')});
  await page.keyboard.press('Escape');
  await page.getByText('Supporting files (1)',{exact:true}).click(); await page.getByRole('button',{name:'Supporting test data',exact:true}).click();
  assert.equal(await page.locator('.wb-dialog .result-supporting-data').count(),1); assert.equal(await page.locator('.wb-dialog .result-supporting-data pre').isVisible(),false);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Verification files', exact: true }).click();
  await page.locator('.archive-content .result-full-image').waitFor();
  assert.equal(await page.locator('.archive-files [data-wb=archive-entry]').count(), 3);
  await page.locator('[data-entry="1"]').click(); await page.locator('.archive-content .result-markdown h1').waitFor();
  assert.equal(await page.locator('.archive-content table').count(), 1);
  await page.screenshot({ path: path.join(out, 'windows-archive.png') });
  await page.locator('.wb-dialog [data-wb=preview]').click(); await page.locator('.code-change summary').first().click(); await page.locator('.code-diff').waitFor();
  assert.match(await page.locator('.code-diff').innerText(), /saveChatAtStart/);
  await page.screenshot({ path: path.join(out, 'windows-diff.png') });
  await page.keyboard.press('Escape');
  await page.locator(`[data-result-select="${archive.id}"]`).check(); await page.locator('[data-wb=delete-selected]').click();
  await page.locator(`[data-result-select="${archive.id}"]`).waitFor({ state: 'detached' });
  assert.equal(fs.existsSync(path.join(profile, 'results', archive.id)), false, 'Windows must remove the saved archive folder');
  assert.ok(fs.existsSync(source), 'The project original stays in place');
  await page.reload(); await page.locator('.session-grid').waitFor();
  assert.deepEqual(new Set((await call('state')).workbench.results.map(x => x.id)), new Set([code.id,...pictures.map(x=>x.id),metadata.id]));
  await openPage(page, 'results'); await page.locator('[data-wb=delete-batch]').click();
  await page.locator('.result-card').first().waitFor({ state: 'detached' });
  assert.equal(fs.existsSync(path.join(profile, 'results', code.id)), false);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(profile, 'results/index.json'), 'utf8')), []);
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(out, 'desktop-check.json'), JSON.stringify({ passed: true, zipImage: true, zipMarkdown: true, branch: true, codeDiff: true, individualAndBatchDeletion: true, savedDirectoriesGone: true, originalKept: true, reloadVerified: true }, null, 2));
  console.log('PASS real Windows ZIP/Markdown previews, branch/diff links, saved-file deletion, and reload');
  await call('quit'); await app.close(); app = null;
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await app?.close().catch(() => {});
  assert.equal(path.dirname(fs.realpathSync(work)), fs.realpathSync(parent)); fs.rmSync(work, { recursive: true, force: true });
});
