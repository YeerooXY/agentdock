'use strict';
// Clicks a file path printed in a real console and checks the in-app preview.
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dataDir = fs.mkdtempSync(path.join(root, 'test-data', 'preview-'));
const out = path.join(root, 'artifacts', 'file-preview'); fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(dataDir, 'settings.json'), JSON.stringify({ setupComplete: true, firstRunComplete: true }));
(async () => {
  const app = await electron.launch({ args: [root, '--smoke-test', `--data-dir=${dataDir}`], env: { ...process.env, NO_COLOR: '1' }, timeout: 30000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('.session-grid');
  await page.setViewportSize({ width: 1240, height: 800 });
  const invoke = (m, p) => page.evaluate(async ([m, p]) => { const r = await window.dock.call(m, p); if (!r.ok) throw new Error(r.error); return r.value; }, [m, p]);
  const session = await invoke('session.create', { provider: 'shell', cwd: root, name: 'Paths' });
  const term = page.locator(`.terminal-instance[data-terminal-id="${session.id}"]`);
  await term.click();
  await page.keyboard.type("Write-Host 'docs\\screenshot-spot.md'; Write-Host 'missing\\nothing-here.txt'\r");
  const row = name => term.locator('.xterm-rows > div', { hasText: new RegExp('^' + name) }).first();
  await row('docs').waitFor();
  const box = await row('docs').boundingBox();
  await page.mouse.move(box.x + 20, box.y + box.height / 2); await page.waitForTimeout(200);
  await page.mouse.click(box.x + 20, box.y + box.height / 2);
  await page.waitForSelector('#file-preview[open]');
  assert.equal(await page.locator('#file-preview-title').textContent(), 'screenshot-spot.md');
  assert.ok(await page.locator('#file-preview .markdown h1').count(), 'Markdown is rendered');
  await page.screenshot({ path: path.join(out, 'markdown-1240.png') });
  await page.setViewportSize({ width: 760, height: 640 });
  await page.screenshot({ path: path.join(out, 'markdown-760.png') });
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#file-preview').open);
  await page.setViewportSize({ width: 1240, height: 800 });
  const missing = await row('missing').boundingBox();
  await page.mouse.move(missing.x + 20, missing.y + missing.height / 2); await page.waitForTimeout(200);
  await page.mouse.click(missing.x + 20, missing.y + missing.height / 2);
  await page.waitForFunction(() => /File not found/.test(document.querySelector('#toast').textContent));
  assert.deepEqual(errors, []);
  console.log('PASS file preview: printed path opens rendered Markdown, Escape closes, missing file shows an error');
  await app.close();
  fs.rmSync(dataDir, { recursive: true, force: true });
})().catch(error => { console.error(error); process.exit(1); });
