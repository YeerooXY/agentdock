'use strict';
// Writes the good and bad versions of the fixture shop, runs every UI rule on both and records a comparison.
// Usage: node scripts/ui-rules-showcase.cjs [output folder, default test-data/ui-rules]
const fs = require('node:fs'), http = require('node:http'), path = require('node:path');
const { build } = require('../tests/fixtures/ui-rules-site.cjs');
const { inspectSources } = require('../electron/ui-source-rules.cjs');
const { inspectInterface, probeInteraction } = require('../electron/ui-rules.cjs');
const { inspectCraft } = require('../electron/ui-craft-rules.cjs');
const { reviewRuntime } = require('../electron/review-browser.cjs');

const VIEWS = [
  { name: 'Desktop', viewport: { width: 1440, height: 1000 } },
  { name: 'Phone', viewport: { width: 390, height: 664 }, isMobile: true, hasTouch: true },
  { name: 'Desktop dark', viewport: { width: 1440, height: 1000 }, query: '?theme=dark' }
];

function writeSite(root, variant) {
  const folder = path.join(root, variant); fs.mkdirSync(folder, { recursive: true });
  for (const [file, content] of Object.entries(build(variant))) fs.writeFileSync(path.join(folder, file), content);
  return folder;
}

function serve(root) {
  const types = { '.html': 'text/html', '.css': 'text/css', '.png': 'image/png' };
  const server = http.createServer((req, res) => {
    const file = path.join(root, decodeURIComponent(new URL(req.url, 'http://x').pathname).replace(/\/$/, '/index.html'));
    if (!file.startsWith(root) || !fs.existsSync(file)) { res.statusCode = 404; return res.end(); }
    res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream'); res.end(fs.readFileSync(file));
  });
  return new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve(server)));
}

async function check(browser, base, variant, shots) {
  const found = new Map(), add = (id, where, count) => { const row = found.get(id) || {}; row[where] = count; found.set(id, row); };
  for (const f of inspectSources(path.join(shots, '..', variant)).findings) add(f.id, 'Source', f.count);
  for (const view of VIEWS) {
    const context = await browser.newContext({ viewport: view.viewport, isMobile: !!view.isMobile, hasTouch: !!view.hasTouch });
    const page = await context.newPage();
    await page.goto(`${base}/${variant}/${view.query || ''}`, { waitUntil: 'load' });
    for (const f of [...(await page.evaluate(inspectInterface)).findings, ...(await page.evaluate(inspectCraft)).findings]) add(f.id, view.name, f.count);
    await page.addStyleTag({ content: '*,*::before,*::after { animation:none!important; transition:none!important; }' });
    await page.screenshot({ fullPage: true, path: path.join(shots, `${variant}-${view.name.toLowerCase().replace(/ /g, '-')}.png`) });
    if (view.name === 'Desktop') for (const f of (await probeInteraction(page)).findings) add(f.id, 'Keyboard/mouse', f.count);
    await context.close();
  }
  return found;
}

async function main(out = path.join(__dirname, '..', 'test-data', 'ui-rules')) {
  out = path.resolve(out);
  const shots = path.join(out, 'screenshots'); fs.mkdirSync(shots, { recursive: true });
  writeSite(out, 'good'); writeSite(out, 'bad');
  const server = await serve(out), base = `http://127.0.0.1:${server.address().port}`;
  const browser = await reviewRuntime().chromium.launch({ headless: true, chromiumSandbox: true });
  try {
    const good = await check(browser, base, 'good', shots), bad = await check(browser, base, 'bad', shots);
    const ids = [...new Set([...bad.keys(), ...good.keys()])].sort();
    const cell = row => row ? Object.entries(row).map(([where, n]) => `${where} ${n}`).join(', ') : 'none';
    const lines = ['# UI rules: good and bad versions of one page', '', 'Generated by `node scripts/ui-rules-showcase.cjs`. Each cell lists where the rule fired and how many elements or lines it flagged.', '',
      '| Rule | Good page | Bad page |', '| --- | --- | --- |', ...ids.map(id => `| \`${id}\` | ${cell(good.get(id))} | ${cell(bad.get(id))} |`), '',
      `Bad page: ${bad.size} rules fired. Good page: ${good.size} rules fired.`, '',
      'Screenshots: `screenshots/good-*.png` and `screenshots/bad-*.png` (desktop, phone, desktop dark).', '',
      'Not checkable from one snapshot: blurring an icon as it swaps out (filter: blur(4px)) is a motion between two states.'];
    fs.writeFileSync(path.join(out, 'REPORT.md'), lines.join('\n') + '\n');
    process.stdout.write(lines.join('\n') + '\n');
    return { good, bad };
  } finally { await browser.close(); server.close(); }
}

if (require.main === module) main(process.argv[2]).catch(error => { process.stderr.write(error.stack + '\n'); process.exit(1); });
module.exports = { main };
