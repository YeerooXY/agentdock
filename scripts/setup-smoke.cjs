'use strict';
const { openPage } = require('./ui-navigation.cjs');
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const shellCommand = require('./shell-commands.cjs');
const root = path.resolve(__dirname, '..'), parent = path.join(root, 'test-data');
fs.mkdirSync(parent, { recursive: true });
const work = fs.mkdtempSync(path.join(parent, 'setup-desktop-')), profile = path.join(work, 'profile'); fs.mkdirSync(profile);
const executablePath = process.argv.find(arg => arg.startsWith('--app='))?.slice(6);
let app;
(async () => {
  app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: [...(executablePath ? [] : [root]), '--smoke-test', `--data-dir=${profile}`], timeout: 30000 });
  const page = await app.firstWindow(); page.setDefaultTimeout(15000); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const call = (method, payload) => page.evaluate(async ([m, p]) => { const r = await window.dock.call(m, p); if (!r.ok) throw Error(r.error); return r.value; }, [method, payload]);
  await page.locator('#first-run[open]').waitFor();
  const state = await call('state'); assert.equal(state.agents.length, 14);
  assert.equal(await page.locator('[data-install-agent]:checked').count(), 0);
  assert.equal(await page.locator('#first-run-title').textContent(), 'Set up Paddock.');
  assert.equal(await page.locator('#first-run-hint').textContent(), 'Choose a project folder and default console.');
  const qwen = state.agents.find(agent => agent.id === 'qwen'); assert.ok(qwen);
  assert.match(qwen.auth, /Qwen OAuth ended April 15, 2026/);
  const qwenChoice = page.locator('[data-setup-agent="qwen"] input');
  assert.equal(await qwenChoice.isDisabled(), false, 'Qwen can be selected for installation on this host');
  await qwenChoice.check();
  await page.locator('#first-run-form [name=provider]').selectOption('qwen');
  assert.equal(await page.locator('#first-run-form [name=provider]').inputValue(), 'qwen');
  assert.match(await page.locator('#setup-agent-hint').textContent(), /Qwen OAuth ended April 15, 2026/);
  assert.equal(await page.locator('[data-setup-guide]').getAttribute('data-docs'), 'qwen');
  await qwenChoice.uncheck();
  await page.locator('#first-run-form [name=provider]').selectOption('shell');
  await assert.rejects(call('agents.install', ['pi']), /disabled during tests/);
  const form = page.locator('#first-run-form');
  await form.locator('[name=cwd]').fill(work); await form.locator('[name=provider]').selectOption('shell'); await form.locator('[name=launchNow]').check();
  await form.locator('[name=mobileSetup]').check();
  await form.locator('[type=submit]').click(); await page.locator('#first-run').waitFor({ state: 'hidden' });
  await page.locator('.mobile-setup[open]').waitFor();
  assert.equal(await page.locator('#mobile-mode').count(), 0, 'Phones connect only through Tailscale; there is no Wi-Fi choice');
  await page.locator('[data-mobile=next]').click(); assert.match(await page.locator('.mobile-setup .form-error').textContent(), /Enable your connection/);
  // Without a 100.x address the step explains how to get one; it never offers a Wi-Fi address for Tailscale.
  const tailscaleHosts = await page.locator('#mobile-host option').evaluateAll(options => options.map(o => o.value));
  assert.ok(tailscaleHosts.every(host => /^100\./.test(host)), 'Only Tailscale addresses are listed');
  if (!tailscaleHosts.length) assert.match(await page.locator('.mobile-step').textContent(), /No Tailscale address found/);
  assert.equal(await page.locator('[data-docs=tailscale]').count(), 1);
  await assert.rejects(call('mobile.configure', { enabled: true, host: '127.0.0.1', mode: 'internet' }), /replaced by Tailscale/);
  await assert.rejects(call('mobile.configure', { enabled: true, host: '127.0.0.1', mode: 'local' }), /Same Wi-Fi connections were removed/);
  await assert.rejects(call('mobile.configure', { enabled: true, host: '127.0.0.1' }), /Tailscale address/);
  await page.locator('[data-mobile=close]').first().click();
  const opened = (await call('state')).sessions.filter(x => x.alive);
  assert.equal(opened.length, 1); assert.equal(opened[0].cwd, work); assert.equal(opened[0].provider, 'shell');
  await call('session.input', { id: opened[0].id, data: shellCommand.shortPrompt(shellCommand.join('SETUP_', 'LAUNCH_OK')) + '\r' });
  await page.waitForFunction(async id => (await window.dock.call('session.buffer', id)).value.data.includes('SETUP_LAUNCH_OK'), opened[0].id);
  await openPage(page, 'console-settings'); await page.locator('[data-action=agent-setup]').click();
  await page.keyboard.press('Escape'); assert.equal(await page.locator('#first-run').isVisible(), false);
  assert.equal((await call('state')).sessions.filter(x => x.alive).length, 1, 'Reopening setup does not launch or end consoles');

  // Prepare with the agent-facing service, then apply through the real UI after restart.
  await app.close(); app = null;
  const { SharedHub } = require('../electron/shared.cjs');
  const { SetupRequests } = require('../electron/setup-requests.cjs');
  const hub = new SharedHub(profile, { list: () => [] });
  new SetupRequests(profile, { getHub: () => hub }).prepare({ kind: 'api', config: { id: 'testapi', name: 'Prepared API', protocol: 'chat', url: 'https://example.com/v1/chat/completions' } }, { consoleName: 'Setup check' });
  app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: [...(executablePath ? [] : [root]), '--smoke-test', `--data-dir=${profile}`], timeout: 30000 });
  const second = await app.firstWindow(); second.setDefaultTimeout(15000);
  await second.locator('.session-grid').waitFor();
  await openPage(second, 'tools');
  await second.locator('[data-integration=rea]').getByRole('heading', { name: 'Reverse Engineer Anything', exact: true }).waitFor();
  await second.locator('[data-integration=mirofish]').getByRole('heading', { name: 'MiroFish', exact: true }).waitFor();
  await second.locator('.creative-tools summary').click();
  await second.locator('[data-creative-prepare=photocraft]').click();
  assert.equal(await second.locator('#tool-form [name=id]').inputValue(), 'photocraft');
  assert.equal(await second.locator('#tool-form [name=enabled]').isChecked(), false);
  assert.equal((await second.evaluate(async () => (await window.dock.call('state')).value)).shared.connections.length, 0);
  await second.locator('[data-action=reset-tool]').click();
  await second.getByRole('heading', { name: 'Prepared API' }).waitFor();
  await second.locator('[data-setup-apply]').click();
  await second.waitForFunction(async () => (await window.dock.call('state')).value.shared.profiles.some(x => x.id === 'testapi'));
  await second.waitForFunction(async () => (await window.dock.call('state')).value.workbench.setupRequests.length === 0);
  assert.deepEqual(errors, []);
  console.log('PASS: optional setup, launch immediately in the chosen folder, manual reopen, installation guard, persisted agent request and Apply. No third-party installs or paid requests.');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (app) await app.close().catch(() => {});
  assert.equal(path.dirname(fs.realpathSync(work)), fs.realpathSync(parent)); fs.rmSync(work, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
});
